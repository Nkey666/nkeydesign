// Кривые анимаций проекта — в одном месте, с понятными именами.
//
// Кортеж [x1, y1, x2, y2] — это контрольные точки cubic-bezier,
// тот же формат, что и в CSS transition-timing-function. Держим их здесь,
// чтобы движение по всему сайту было согласованным: меняешь кривую в одном
// месте — меняется везде. Значение EASE_OUT совпадает с CSS-переменной
// --ease-smooth в globals.css, поэтому анимации в JS (motion) и CSS-переходы
// ощущаются одинаково.

/** Основной мягкий «выезд» — появления блоков, ховеры, модалки. */
export const EASE_OUT = [0.22, 1, 0.36, 1] as const;

/** Более резкий выезд с длинным хвостом — прочерчивание подчёркивания. */
export const EASE_OUT_EXPO = [0.16, 1, 0.3, 1] as const;

/** Длинный плавный разгон-торможение — проезд луча по таймлайну. */
export const EASE_IN_OUT = [0.45, 0, 0.15, 1] as const;

/** Лёгкий «отскок» за единицу и назад — пульс точки этапа. */
export const EASE_BACK = [0.34, 1.56, 0.64, 1] as const;
